def pchip_smooth(x, y, num=500):
    """Monotone cubic interpolation (fallback to linear interp if scipy is unavailable)."""
    x_new = np.linspace(min(x), max(x), num)
    try:
        from scipy.interpolate import PchipInterpolator
        return x_new, PchipInterpolator(x, y)(x_new)
    except Exception:
        return x_new, np.interp(x_new, x, y)


def main():
    parser = argparse.ArgumentParser(description="Plot DOKDO training loss curve")
    parser.add_argument("--metrics_pt", type=str, default=None,
                        help="Optional path to train_metrics.pt generated by Train/train.py")
    parser.add_argument("--out", type=str, default=DEFAULT_OUT,
                        help="Output PNG path (default: assets/training_curve.png)")
    args = parser.parse_args()

    if args.metrics_pt and os.path.isfile(args.metrics_pt):
        import torch
        hist = torch.load(args.metrics_pt, map_location="cpu", weights_only=False)
        epochs = hist["epochs"]
        train_loss = hist["train_loss"]
        val_loss = hist["val_loss"]
    else:
        epochs, train_loss, val_loss = zip(*PAPER_TRAJECTORY)

    x_new, train_smooth = pchip_smooth(epochs, train_loss, 500)
    _, val_smooth = pchip_smooth(epochs, val_loss, 500)

    plt.rcParams["axes.unicode_minus"] = False
    plt.rcParams["axes.linewidth"] = 1.2
    plt.rcParams["font.size"] = 13

    fig, ax = plt.subplots(figsize=(9.5, 4.8), dpi=200)

    color_val = "#2980B9"
    color_train = "#E67E22"

    ax.axhline(y=1.1027, color="#888888", linestyle="--", linewidth=1.2, alpha=0.6, zorder=1)
    ax.text(2.5, 0.72, "Best Val Convergence (Epoch 95: 1.1027)", fontsize=11, style="italic", color="#555555")

    ax.plot(x_new, train_smooth, "-", color=color_train, linewidth=2.2, label="Train Loss (0.3 CTC + 0.7 CE)", zorder=3)
    ax.plot(x_new, val_smooth, "-", color=color_val, linewidth=2.2, label="Validation Loss", zorder=3)

    ax.set_ylim(0, 8.2)
    ax.set_xlim(0, max(epochs) + 2)

    # Phase 1: Frozen Encoder (Epoch 1-5)
    ax.axvspan(0, 5.5, facecolor="#7f8c8d", alpha=0.14)
    ax.text(2.75, 7.55, "Phase 1\n(Freeze 1-5)", fontsize=11, ha="center", va="center", fontweight="bold", color="#333333")

    # Phase 2: Full Fine-tuning with Differential LR (Epoch 6-95)
    ax.text(50, 7.55, "Phase 2: Full Fine-Tuning (OLKAVS, Differential LR 1e-5 / 1e-3)", fontsize=12, ha="center", va="center", fontweight="bold", color="#333333")

    # Stage 2: KMSAV Domain Adaptation
    if max(epochs) >= 96:
        ax.axvspan(95.2, max(epochs) + 2, facecolor="#27ae60", alpha=0.14)
        ax.text(94.5, 7.55, "KMSAV Adaptation ->", fontsize=11, ha="right", va="center", fontweight="bold", color="#1e711e")

    ax.legend(fontsize=11.5, loc="upper right", frameon=True, facecolor="white", framealpha=0.85, edgecolor="#dddddd")
    ax.set_xlabel("Epochs", fontsize=13, fontweight="bold", color="#333333")
    ax.set_ylabel("Hybrid Loss", fontsize=13, fontweight="bold", color="#333333")
    ax.set_title("DOKDO Two-Stage Transfer Learning & Domain Adaptation Convergence", fontsize=13.5, fontweight="bold", pad=12, color="#222222")

    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.spines["left"].set_color("#bbbbbb")
    ax.spines["bottom"].set_color("#bbbbbb")
    ax.grid(axis="y", linestyle="-", alpha=0.3, color="#cccccc")

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    plt.tight_layout()
    plt.savefig(args.out, dpi=200)
    print(f"Saved training curve to {args.out}")


if __name__ == "__main__":
    main()
